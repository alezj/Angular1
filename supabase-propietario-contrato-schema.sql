-- Datos de comparecientes para contratos. Aplicar después de supabase-garantes-schema.sql.
BEGIN;
CREATE TABLE IF NOT EXISTS public.propietario (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "nombreCompleto" TEXT NOT NULL CHECK (length(trim("nombreCompleto")) BETWEEN 1 AND 200),
  cedula TEXT NOT NULL CHECK (length(trim(cedula)) BETWEEN 1 AND 30),
  nacionalidad TEXT NOT NULL CHECK (length(trim(nacionalidad)) BETWEEN 1 AND 80),
  direccion TEXT NOT NULL CHECK (length(trim(direccion)) BETWEEN 1 AND 500),
  "mayorEdad" BOOLEAN NOT NULL CHECK ("mayorEdad"),
  telefono TEXT,
  correo TEXT,
  usuario UUID NOT NULL DEFAULT auth.uid(),
  company_id UUID,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  UNIQUE (id, company_id)
);
CREATE UNIQUE INDEX IF NOT EXISTS propietario_cedula_scope_key ON public.propietario
  (coalesce(company_id, usuario), lower(regexp_replace(cedula, '[^[:alnum:]]', '', 'g')));
CREATE INDEX IF NOT EXISTS propietario_company_idx ON public.propietario (company_id);
CREATE INDEX IF NOT EXISTS propietario_usuario_idx ON public.propietario (usuario);
ALTER TABLE public.propietario ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON public.propietario FROM PUBLIC, anon;
GRANT SELECT, INSERT, UPDATE, DELETE ON public.propietario TO authenticated;
GRANT USAGE, SELECT ON SEQUENCE public.propietario_id_seq TO authenticated;
ALTER TABLE public.inquilinos
  ADD COLUMN IF NOT EXISTS cedula TEXT,
  ADD COLUMN IF NOT EXISTS nacionalidad TEXT,
  ADD COLUMN IF NOT EXISTS direccion TEXT,
  ADD COLUMN IF NOT EXISTS "mayorEdad" BOOLEAN;
-- Los datos de identidad requieren sesión, también en el ambiente de prueba.
REVOKE ALL ON public.inquilinos FROM PUBLIC, anon;
GRANT SELECT, INSERT, UPDATE, DELETE ON public.inquilinos TO authenticated;
ALTER TABLE public.alquileres ADD COLUMN IF NOT EXISTS "propietarioID" BIGINT
  REFERENCES public.propietario(id) ON DELETE RESTRICT;
CREATE INDEX IF NOT EXISTS alquileres_propietario_idx ON public.alquileres ("propietarioID");

DO $$
DECLARE lectura TEXT; alta TEXT; cambio TEXT; baja TEXT; definicion TEXT;
BEGIN
  IF EXISTS (SELECT 1 FROM information_schema.columns WHERE table_schema='public'
    AND table_name='alquileres' AND column_name='company_id') THEN
    ALTER TABLE public.propietario ALTER COLUMN company_id SET NOT NULL;
    IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conrelid='public.propietario'::regclass AND conname='propietario_company_fkey') THEN
      ALTER TABLE public.propietario ADD CONSTRAINT propietario_company_fkey FOREIGN KEY (company_id) REFERENCES public.companies(id);
      CREATE TRIGGER set_company_id BEFORE INSERT OR UPDATE ON public.propietario
        FOR EACH ROW EXECUTE FUNCTION public.set_business_company_id();
      ALTER TABLE public.alquileres ADD CONSTRAINT alquileres_propietario_company_fkey
        FOREIGN KEY ("propietarioID", company_id) REFERENCES public.propietario(id, company_id);
    END IF;
    lectura := '(private.has_business_permission(company_id, ''propiedades'', ''read'') OR private.has_business_permission(company_id, ''alquileres'', ''read''))';
    alta := 'private.has_business_permission(company_id, ''propiedades'', ''create'')';
    cambio := 'private.has_business_permission(company_id, ''propiedades'', ''update'')';
    baja := 'private.has_business_permission(company_id, ''propiedades'', ''delete'')';
  ELSE
    lectura := 'usuario = (select auth.uid())';
    alta := lectura; cambio := lectura; baja := lectura;
  END IF;
  IF NOT EXISTS (SELECT 1 FROM pg_policies WHERE schemaname='public' AND tablename='propietario') THEN
    EXECUTE 'CREATE POLICY propietario_select ON public.propietario FOR SELECT TO authenticated USING (' || lectura || ')';
    EXECUTE 'CREATE POLICY propietario_insert ON public.propietario FOR INSERT TO authenticated WITH CHECK (' || alta || ')';
    EXECUTE 'CREATE POLICY propietario_update ON public.propietario FOR UPDATE TO authenticated USING (' || cambio || ') WITH CHECK (' || cambio || ')';
    EXECUTE 'CREATE POLICY propietario_delete ON public.propietario FOR DELETE TO authenticated USING (' || baja || ')';
  END IF;
  SELECT pg_get_functiondef('public.guardar_contrato_con_garantes(jsonb,jsonb,bigint)'::regprocedure) INTO definicion;
  IF strpos(definicion, '''propietarioID''') = 0 THEN
    definicion := replace(definicion, '''propiedadID'',''inquilinoID''', '''propietarioID'',''propiedadID'',''inquilinoID''');
    definicion := replace(definicion, '  -- Compatibilidad con clientes anteriores', $check$
  IF p_datos->>'propietarioID' IS NOT NULL AND NOT EXISTS (
    SELECT 1 FROM public.propietario WHERE id = (p_datos->>'propietarioID')::bigint
  ) THEN RAISE EXCEPTION 'Propietario no disponible o sin permiso de acceso.'; END IF;
  -- Compatibilidad con clientes anteriores$check$);
    EXECUTE definicion;
  END IF;
END $$;
NOTIFY pgrst, 'reload schema';
COMMIT;
