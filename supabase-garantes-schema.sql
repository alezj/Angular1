-- Varios garantes por contrato. Ejecutar en prueba y producción.
-- Mantiene los campos anteriores del primer garante por compatibilidad.
BEGIN;

CREATE TABLE IF NOT EXISTS public.garantes (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  alquiler_id BIGINT NOT NULL REFERENCES public.alquileres(id) ON DELETE CASCADE,
  cedula TEXT NOT NULL CHECK (length(trim(cedula)) BETWEEN 1 AND 30),
  nombre_completo TEXT NOT NULL CHECK (length(trim(nombre_completo)) BETWEEN 1 AND 200),
  created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE UNIQUE INDEX IF NOT EXISTS garantes_contrato_cedula_key
  ON public.garantes (alquiler_id, lower(regexp_replace(cedula, '[^[:alnum:]]', '', 'g')));
ALTER TABLE public.garantes ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON public.garantes FROM anon;
GRANT SELECT, INSERT, UPDATE, DELETE ON public.garantes TO authenticated;
GRANT USAGE, SELECT ON SEQUENCE public.garantes_id_seq TO authenticated;

-- Producción usa permisos por empresa. Prueba usa el usuario del contrato.
DO $$
DECLARE permiso_lectura TEXT; permiso_escritura TEXT; permiso_alta TEXT;
BEGIN
  IF EXISTS (SELECT 1 FROM information_schema.columns
    WHERE table_schema = 'public' AND table_name = 'alquileres' AND column_name = 'company_id') THEN
    permiso_lectura := 'EXISTS (SELECT 1 FROM public.alquileres a WHERE a.id = alquiler_id AND private.has_business_permission(a.company_id, ''alquileres'', ''read''))';
    permiso_escritura := 'EXISTS (SELECT 1 FROM public.alquileres a WHERE a.id = alquiler_id AND private.has_business_permission(a.company_id, ''alquileres'', ''update''))';
    permiso_alta := 'EXISTS (SELECT 1 FROM public.alquileres a WHERE a.id = alquiler_id AND (private.has_business_permission(a.company_id, ''alquileres'', ''create'') OR private.has_business_permission(a.company_id, ''alquileres'', ''update'')))';
  ELSE
    permiso_lectura := 'EXISTS (SELECT 1 FROM public.alquileres a WHERE a.id = alquiler_id AND a.usuario = (select auth.uid()))';
    permiso_escritura := permiso_lectura;
    permiso_alta := permiso_lectura;
  END IF;
  IF NOT EXISTS (SELECT 1 FROM pg_policies WHERE schemaname = 'public' AND tablename = 'garantes' AND policyname = 'garantes_select') THEN
    EXECUTE 'CREATE POLICY garantes_select ON public.garantes FOR SELECT TO authenticated USING (' || permiso_lectura || ')';
    EXECUTE 'CREATE POLICY garantes_insert ON public.garantes FOR INSERT TO authenticated WITH CHECK (' || permiso_alta || ')';
    EXECUTE 'CREATE POLICY garantes_update ON public.garantes FOR UPDATE TO authenticated USING (' || permiso_escritura || ') WITH CHECK (' || permiso_escritura || ')';
    EXECUTE 'CREATE POLICY garantes_delete ON public.garantes FOR DELETE TO authenticated USING (' || permiso_escritura || ')';
  END IF;
END $$;

INSERT INTO public.garantes (alquiler_id, cedula, nombre_completo)
SELECT id, trim("garanteCedula"), trim("garanteNombreCompleto")
FROM public.alquileres
WHERE nullif(trim("garanteCedula"), '') IS NOT NULL
  AND nullif(trim("garanteNombreCompleto"), '') IS NOT NULL
ON CONFLICT DO NOTHING;

-- Una llamada, una transacción: ningún contrato queda guardado a medias.
-- SECURITY INVOKER mantiene las políticas RLS del usuario que llama.
CREATE OR REPLACE FUNCTION public.guardar_contrato_con_garantes(
  p_datos JSONB, p_garantes JSONB, p_id BIGINT DEFAULT NULL
) RETURNS JSONB
LANGUAGE plpgsql SECURITY INVOKER SET search_path = '' AS $$
DECLARE
  columnas TEXT; valores TEXT; asignaciones TEXT;
  contrato public.alquileres;
  entrada JSONB;
BEGIN
  IF auth.uid() IS NULL THEN RAISE EXCEPTION 'Se requiere una sesión autenticada.'; END IF;
  IF jsonb_typeof(p_datos) IS DISTINCT FROM 'object'
    OR jsonb_typeof(p_garantes) IS DISTINCT FROM 'array' THEN
    RAISE EXCEPTION 'Datos de contrato o garantes inválidos.';
  END IF;
  FOR entrada IN SELECT value FROM jsonb_array_elements(p_garantes) LOOP
    IF jsonb_typeof(entrada) IS DISTINCT FROM 'object'
      OR nullif(trim(entrada->>'cedula'), '') IS NULL
      OR nullif(trim(entrada->>'nombre_completo'), '') IS NULL THEN
      RAISE EXCEPTION 'Completa la cédula y el nombre de cada garante.';
    END IF;
  END LOOP;
  -- Compatibilidad con clientes anteriores, sin eliminar sus columnas.
  p_datos := p_datos || jsonb_build_object(
    'garanteCedula', p_garantes->0->>'cedula',
    'garanteNombreCompleto', p_garantes->0->>'nombre_completo');
  -- Lista explícita: no se permite modificar identidad, usuario ni empresa.
  -- Se intersecta con el esquema porque prueba no tiene todas las condiciones de producción.
  SELECT string_agg(format('%I', a.attname), ', '),
    string_agg(format('v.%I', a.attname), ', '),
    string_agg(format('%I = v.%I', a.attname, a.attname), ', ')
  INTO columnas, valores, asignaciones
  FROM pg_catalog.pg_attribute a
  WHERE a.attrelid = 'public.alquileres'::regclass AND a.attnum > 0 AND NOT a.attisdropped
    AND p_datos ? a.attname
    AND a.attname = ANY(ARRAY['propiedadID','inquilinoID','fechaInicio','fechaFin','montoPago',
      'importe','cantidadDepositos','diaPago','cantidadMeses','diasProrroga',
      'garanteCedula','garanteNombreCompleto']);
  IF p_id IS NULL THEN
    EXECUTE format('INSERT INTO public.alquileres (%s) SELECT %s FROM jsonb_populate_record(NULL::public.alquileres, $1) v RETURNING *', columnas, valores)
      INTO contrato USING p_datos;
  ELSE
    EXECUTE format('UPDATE public.alquileres a SET %s FROM jsonb_populate_record(NULL::public.alquileres, $1) v WHERE a.id = $2 RETURNING a.*', asignaciones)
      INTO contrato USING p_datos, p_id;
    IF contrato.id IS NULL THEN RAISE EXCEPTION 'Contrato no encontrado o sin permiso para editar.'; END IF;
    DELETE FROM public.garantes WHERE alquiler_id = contrato.id;
    IF EXISTS (SELECT 1 FROM public.garantes WHERE alquiler_id = contrato.id) THEN
      RAISE EXCEPTION 'No tienes permiso para reemplazar los garantes.';
    END IF;
  END IF;
  INSERT INTO public.garantes (alquiler_id, cedula, nombre_completo)
    SELECT contrato.id, trim(value->>'cedula'), trim(value->>'nombre_completo')
    FROM jsonb_array_elements(p_garantes);
  RETURN to_jsonb(contrato) || jsonb_build_object('garantes',
    (SELECT coalesce(jsonb_agg(to_jsonb(g) ORDER BY g.id), '[]'::jsonb)
      FROM public.garantes g WHERE g.alquiler_id = contrato.id));
END $$;
REVOKE ALL ON FUNCTION public.guardar_contrato_con_garantes(JSONB, JSONB, BIGINT) FROM PUBLIC, anon;
GRANT EXECUTE ON FUNCTION public.guardar_contrato_con_garantes(JSONB, JSONB, BIGINT) TO authenticated;
NOTIFY pgrst, 'reload schema';
COMMIT;
