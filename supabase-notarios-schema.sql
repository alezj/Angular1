-- Catálogo notarial y certificación por contrato.
-- Aplicar después de supabase-alquileres-depositos-firma-schema.sql.
-- Validado en Alquilados_Test; aplicar a producción al desplegar esta funcionalidad.
BEGIN;
CREATE TABLE IF NOT EXISTS public.notario (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "nombreCompleto" TEXT NOT NULL CHECK (length(trim("nombreCompleto")) BETWEEN 1 AND 200),
  cedula TEXT NOT NULL CHECK (length(trim(cedula)) BETWEEN 1 AND 30 AND cedula ~ '[[:alnum:]]'),
  matricula TEXT NOT NULL CHECK (length(trim(matricula)) BETWEEN 1 AND 30 AND matricula ~ '[[:alnum:]]'),
  jurisdiccion TEXT NOT NULL CHECK (length(trim(jurisdiccion)) BETWEEN 1 AND 200),
  direccion TEXT NOT NULL CHECK (length(trim(direccion)) BETWEEN 1 AND 500),
  telefono TEXT CHECK (length(telefono) <= 40),
  correo TEXT CHECK (length(correo) <= 254 AND (correo = '' OR correo ~ '^[^[:space:]@]+@[^[:space:]@]+\.[^[:space:]@]+$')),
  usuario UUID NOT NULL DEFAULT auth.uid(),
  company_id UUID,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  UNIQUE (id, company_id)
);
CREATE UNIQUE INDEX IF NOT EXISTS notario_cedula_scope_key ON public.notario
  (coalesce(company_id, usuario), lower(regexp_replace(cedula, '[^[:alnum:]]', '', 'g')));
CREATE UNIQUE INDEX IF NOT EXISTS notario_matricula_scope_key ON public.notario
  (coalesce(company_id, usuario), lower(regexp_replace(matricula, '[^[:alnum:]]', '', 'g')));
CREATE INDEX IF NOT EXISTS notario_company_idx ON public.notario (company_id);
CREATE INDEX IF NOT EXISTS notario_usuario_idx ON public.notario (usuario);
ALTER TABLE public.notario ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON public.notario FROM PUBLIC, anon;
GRANT SELECT, INSERT, UPDATE, DELETE ON public.notario TO authenticated;
GRANT USAGE, SELECT ON SEQUENCE public.notario_id_seq TO authenticated;
ALTER TABLE public.alquileres
  ADD COLUMN IF NOT EXISTS "notarioID" BIGINT REFERENCES public.notario(id) ON DELETE RESTRICT,
  ADD COLUMN IF NOT EXISTS "lugarCertificacion" TEXT CHECK (length(trim("lugarCertificacion")) BETWEEN 1 AND 200),
  ADD COLUMN IF NOT EXISTS "fechaCertificacion" DATE;
CREATE INDEX IF NOT EXISTS alquileres_notario_idx ON public.alquileres ("notarioID");

DO $$
DECLARE lectura TEXT; alta TEXT; cambio TEXT; baja TEXT; definicion TEXT; actualizada TEXT;
BEGIN
  IF EXISTS (SELECT 1 FROM information_schema.columns WHERE table_schema='public'
    AND table_name='alquileres' AND column_name='company_id') THEN
    ALTER TABLE public.notario ALTER COLUMN company_id SET NOT NULL;
    IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conrelid='public.notario'::regclass AND conname='notario_company_fkey') THEN
      ALTER TABLE public.notario ADD CONSTRAINT notario_company_fkey FOREIGN KEY (company_id) REFERENCES public.companies(id);
      CREATE TRIGGER set_company_id BEFORE INSERT OR UPDATE ON public.notario
        FOR EACH ROW EXECUTE FUNCTION public.set_business_company_id();
      ALTER TABLE public.alquileres ADD CONSTRAINT alquileres_notario_company_fkey
        FOREIGN KEY ("notarioID", company_id) REFERENCES public.notario(id, company_id);
    END IF;
    lectura := 'private.has_business_permission(company_id, ''alquileres'', ''read'')';
    alta := 'private.has_business_permission(company_id, ''alquileres'', ''create'')';
    cambio := 'private.has_business_permission(company_id, ''alquileres'', ''update'')';
    baja := 'private.has_business_permission(company_id, ''alquileres'', ''delete'')';
  ELSE
    lectura := 'usuario = (select auth.uid())';
    alta := lectura; cambio := lectura; baja := lectura;
  END IF;
  IF NOT EXISTS (SELECT 1 FROM pg_policies WHERE schemaname='public' AND tablename='notario') THEN
    EXECUTE 'CREATE POLICY notario_select ON public.notario FOR SELECT TO authenticated USING (' || lectura || ')';
    EXECUTE 'CREATE POLICY notario_insert ON public.notario FOR INSERT TO authenticated WITH CHECK (' || alta || ')';
    EXECUTE 'CREATE POLICY notario_update ON public.notario FOR UPDATE TO authenticated USING (' || cambio || ') WITH CHECK (' || cambio || ')';
    EXECUTE 'CREATE POLICY notario_delete ON public.notario FOR DELETE TO authenticated USING (' || baja || ')';
  END IF;
  SELECT pg_get_functiondef('public.guardar_contrato_con_garantes(jsonb,jsonb,bigint)'::regprocedure) INTO definicion;
  IF strpos(definicion, '''notarioID''') = 0 THEN
    actualizada := replace(definicion, '''propietarioID'',''propiedadID''',
      '''notarioID'',''lugarCertificacion'',''fechaCertificacion'',''propietarioID'',''propiedadID''');
    actualizada := replace(actualizada, '  -- Compatibilidad con clientes anteriores', $check$
  IF p_datos->>'notarioID' IS NOT NULL THEN
    IF NOT EXISTS (SELECT 1 FROM public.notario WHERE id = (p_datos->>'notarioID')::bigint) THEN
      RAISE EXCEPTION 'Notario no disponible o sin permiso de acceso.';
    END IF;
    IF nullif(trim(p_datos->>'lugarCertificacion'), '') IS NULL
      OR nullif(p_datos->>'fechaCertificacion', '') IS NULL THEN
      RAISE EXCEPTION 'Completa el lugar y la fecha de certificación notarial.';
    END IF;
  END IF;
  -- Compatibilidad con clientes anteriores$check$);
    IF strpos(actualizada, '''notarioID'',''lugarCertificacion''') = 0
      OR strpos(actualizada, 'Notario no disponible') = 0 THEN
      RAISE EXCEPTION 'Revisar guardar_contrato_con_garantes antes de aplicar.';
    END IF;
    EXECUTE actualizada;
  END IF;
END $$;
NOTIFY pgrst, 'reload schema';
COMMIT;
