-- 1. TABLA ESTADOS
CREATE TABLE IF NOT EXISTS public.estados (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "Descripcion" TEXT NOT NULL,
    "tabla" TEXT NOT NULL,
    created_at TIMESTAMPTZ DEFAULT NOW()
);

-- Semilla de estados iniciales
INSERT INTO public.estados ("Descripcion", "tabla")
VALUES 
    ('Disponible', 'propiedades'),
    ('Alquilada', 'propiedades'),
    ('Mantenimiento', 'propiedades'),
    ('Inactiva', 'propiedades'),
    ('Pendiente', 'mantenimientos'),
    ('En proceso', 'mantenimientos'),
    ('Finalizado', 'mantenimientos'),
    ('Cancelado', 'mantenimientos')
ON CONFLICT DO NOTHING;

-- 2. TABLA PROPIEDADES
CREATE TABLE IF NOT EXISTS public.propiedades (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "nombre" TEXT NOT NULL,
    "direccion" TEXT NOT NULL,
    "estado" INTEGER DEFAULT 1,
    "precioMensual" NUMERIC DEFAULT 0,
    "notas" TEXT DEFAULT '',
    created_at TIMESTAMPTZ DEFAULT NOW()
);

-- 3. TABLA INQUILINOS
CREATE TABLE IF NOT EXISTS public.inquilinos (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "nombreApellido" TEXT NOT NULL,
    "correo" TEXT DEFAULT '',
    "email" TEXT DEFAULT '',
    "fechaInicioContrato" TEXT DEFAULT '',
    "fechaPagos" INTEGER DEFAULT 1,
    created_at TIMESTAMPTZ DEFAULT NOW()
);

-- 4. TABLA PAGOS
CREATE TABLE IF NOT EXISTS public.pagos (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "idInquilino" BIGINT REFERENCES public.inquilinos(id) ON DELETE SET NULL,
    "fechaPago" TEXT NOT NULL,
    "monto" NUMERIC DEFAULT 0,
    created_at TIMESTAMPTZ DEFAULT NOW()
);

-- 5. TABLA MANTENIMIENTOS
CREATE TABLE IF NOT EXISTS public.mantenimientos (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "propiedadID" BIGINT REFERENCES public.propiedades(id) ON DELETE CASCADE,
    "descripcion" TEXT NOT NULL,
    "fecha" TEXT NOT NULL,
    "costo" NUMERIC DEFAULT 0,
    "estado" INTEGER DEFAULT 1,
    created_at TIMESTAMPTZ DEFAULT NOW()
);

-- 6. TABLA ALQUILERES
CREATE TABLE IF NOT EXISTS public.alquileres (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "propiedadID" BIGINT REFERENCES public.propiedades(id) ON DELETE CASCADE,
    "inquilinoID" BIGINT REFERENCES public.inquilinos(id) ON DELETE CASCADE,
    "fechaInicio" TEXT NOT NULL,
    "fechaFin" TEXT NOT NULL,
    created_at TIMESTAMPTZ DEFAULT NOW()
);

-- ==============================================================================
-- HABILITACIÓN DE ROW LEVEL SECURITY (RLS) Y POLÍTICAS DE ACCESO
-- Permite que el frontend lea y escriba datos mediante el cliente Supabase
-- ==============================================================================

ALTER TABLE public.estados ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.propiedades ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.inquilinos ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.pagos ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.mantenimientos ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.alquileres ENABLE ROW LEVEL SECURITY;

-- Políticas para permitir acceso completo (lectura, inserción, actualización, eliminación)
DO $$
