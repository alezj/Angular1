-- 1. TABLA ESTADOS
CREATE TABLE IF NOT EXISTS public.estados (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    "Origen" TEXT NOT NULL DEFAULT 'web' CHECK ("Origen" IN ('web', 'movil')),
    usuario UUID NOT NULL DEFAULT COALESCE(auth.uid(), '00000000-0000-0000-0000-000000000000'::uuid),
    "Descripcion" TEXT NOT NULL,
    "tabla" TEXT NOT NULL,
    created_at TIMESTAMPTZ DEFAULT NOW(),
    PRIMARY KEY (id, "Origen", usuario),
    CONSTRAINT uq_estados_legacy_id UNIQUE (id)
);

-- Semilla de estados iniciales
INSERT INTO public.estados ("Descripcion", "tabla")
VALUES 
    ('Disponible', 'propiedades'),
    ('Alquilada', 'propiedades'),
    ('Mantenimiento', 'propiedades'),
    ('Inactiva', 'propiedades'),
    ('Pendiente', 'mantenimientos'),
    ('En proceso', 'mantenimientos'),
    ('Finalizado', 'mantenimientos'),
    ('Cancelado', 'mantenimientos')
ON CONFLICT DO NOTHING;

-- 2. TABLA PROPIEDADES
CREATE TABLE IF NOT EXISTS public.propiedades (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    "Origen" TEXT NOT NULL DEFAULT 'web' CHECK ("Origen" IN ('web', 'movil')),
    usuario UUID NOT NULL DEFAULT COALESCE(auth.uid(), '00000000-0000-0000-0000-000000000000'::uuid),
    "codigo" TEXT DEFAULT '',
    "nombre" TEXT NOT NULL,
    "tipo" TEXT DEFAULT '',
    "direccion" TEXT NOT NULL,
    "sector" TEXT DEFAULT '',
    "ciudad" TEXT DEFAULT '',
    "habitaciones" INTEGER DEFAULT 0,
    "banos" NUMERIC DEFAULT 0,
    "parqueos" INTEGER DEFAULT 0,
    "area" NUMERIC DEFAULT 0,
    "estado" INTEGER DEFAULT 1,
    "precioMensual" NUMERIC DEFAULT 0,
    "deposito" NUMERIC DEFAULT 0,
    "imagenUrl" TEXT DEFAULT '',
    "notas" TEXT DEFAULT '',
    created_at TIMESTAMPTZ DEFAULT NOW(),
    PRIMARY KEY (id, "Origen", usuario),
    CONSTRAINT uq_propiedades_legacy_id UNIQUE (id)
);

-- 3. TABLA INQUILINOS
CREATE TABLE IF NOT EXISTS public.inquilinos (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    "Origen" TEXT NOT NULL DEFAULT 'web' CHECK ("Origen" IN ('web', 'movil')),
    usuario UUID NOT NULL DEFAULT COALESCE(auth.uid(), '00000000-0000-0000-0000-000000000000'::uuid),
    "nombreApellido" TEXT NOT NULL,
    "correo" TEXT DEFAULT '',
    "email" TEXT DEFAULT '',
    "fechaInicioContrato" TEXT DEFAULT '',
    "fechaPagos" INTEGER DEFAULT 1,
    created_at TIMESTAMPTZ DEFAULT NOW(),
    PRIMARY KEY (id, "Origen", usuario),
    CONSTRAINT uq_inquilinos_legacy_id UNIQUE (id)
);

-- 4. TABLA PAGOS
CREATE TABLE IF NOT EXISTS public.pagos (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    "Origen" TEXT NOT NULL DEFAULT 'web' CHECK ("Origen" IN ('web', 'movil')),
    usuario UUID NOT NULL DEFAULT COALESCE(auth.uid(), '00000000-0000-0000-0000-000000000000'::uuid),
    "idInquilino" BIGINT REFERENCES public.inquilinos(id) ON DELETE SET NULL,
    "fechaPago" TEXT NOT NULL,
    "monto" NUMERIC DEFAULT 0,
    "idAlquiler" BIGINT,
    "periodo" TEXT,
    "fechaVencimiento" TEXT,
    "estado" TEXT NOT NULL DEFAULT 'Pagado',
    "metodoPago" TEXT,
    "banco" TEXT,
    "referencia" TEXT,
    created_at TIMESTAMPTZ DEFAULT NOW(),
    PRIMARY KEY (id, "Origen", usuario),
    CONSTRAINT uq_pagos_legacy_id UNIQUE (id)
);

-- 5. TABLA MANTENIMIENTOS
CREATE TABLE IF NOT EXISTS public.mantenimientos (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    "Origen" TEXT NOT NULL DEFAULT 'web' CHECK ("Origen" IN ('web', 'movil')),
    usuario UUID NOT NULL DEFAULT COALESCE(auth.uid(), '00000000-0000-0000-0000-000000000000'::uuid),
    "propiedadID" BIGINT REFERENCES public.propiedades(id) ON DELETE CASCADE,
    "descripcion" TEXT NOT NULL,
    "fecha" TEXT NOT NULL,
    "costo" NUMERIC DEFAULT 0,
    "estado" INTEGER DEFAULT 1,
    created_at TIMESTAMPTZ DEFAULT NOW(),
    PRIMARY KEY (id, "Origen", usuario),
    CONSTRAINT uq_mantenimientos_legacy_id UNIQUE (id)
);

-- 6. TABLA ALQUILERES
CREATE TABLE IF NOT EXISTS public.alquileres (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    "Origen" TEXT NOT NULL DEFAULT 'web' CHECK ("Origen" IN ('web', 'movil')),
    usuario UUID NOT NULL DEFAULT COALESCE(auth.uid(), '00000000-0000-0000-0000-000000000000'::uuid),
    "propiedadID" BIGINT REFERENCES public.propiedades(id) ON DELETE CASCADE,
    "inquilinoID" BIGINT REFERENCES public.inquilinos(id) ON DELETE CASCADE,
    "fechaInicio" TEXT NOT NULL,
    "fechaFin" TEXT NOT NULL,
    created_at TIMESTAMPTZ DEFAULT NOW(),
    PRIMARY KEY (id, "Origen", usuario),
    CONSTRAINT uq_alquileres_legacy_id UNIQUE (id)
);

-- ==============================================================================
-- HABILITACIÓN DE ROW LEVEL SECURITY (RLS) Y POLÍTICAS DE ACCESO
-- Permite que el frontend lea y escriba datos mediante el cliente Supabase
-- ==============================================================================

ALTER TABLE public.estados ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.propiedades ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.inquilinos ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.pagos ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.mantenimientos ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.alquileres ENABLE ROW LEVEL SECURITY;

-- Políticas para permitir acceso completo (lectura, inserción, actualización, eliminación)
DO $$
BEGIN
    -- Estados
    DROP POLICY IF EXISTS "Acceso total a estados" ON public.estados;
    CREATE POLICY "Acceso total a estados" ON public.estados FOR ALL TO anon, authenticated USING (true) WITH CHECK (true);

    -- Propiedades
    DROP POLICY IF EXISTS "Acceso total a propiedades" ON public.propiedades;
    CREATE POLICY "Acceso total a propiedades" ON public.propiedades FOR ALL TO anon, authenticated USING (true) WITH CHECK (true);

    -- Inquilinos
    DROP POLICY IF EXISTS "Acceso total a inquilinos" ON public.inquilinos;
    CREATE POLICY "Acceso total a inquilinos" ON public.inquilinos FOR ALL TO anon, authenticated USING (true) WITH CHECK (true);

    -- Pagos
    DROP POLICY IF EXISTS "Acceso total a pagos" ON public.pagos;
    CREATE POLICY "Acceso total a pagos" ON public.pagos FOR ALL TO anon, authenticated USING (true) WITH CHECK (true);

    -- Mantenimientos
    DROP POLICY IF EXISTS "Acceso total a mantenimientos" ON public.mantenimientos;
    CREATE POLICY "Acceso total a mantenimientos" ON public.mantenimientos FOR ALL TO anon, authenticated USING (true) WITH CHECK (true);

    -- Alquileres
    DROP POLICY IF EXISTS "Acceso total a alquileres" ON public.alquileres;
    CREATE POLICY "Acceso total a alquileres" ON public.alquileres FOR ALL TO anon, authenticated USING (true) WITH CHECK (true);
END $$;
