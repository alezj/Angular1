    -- Pagos
    DROP POLICY IF EXISTS "Acceso total a pagos" ON public.pagos;
    CREATE POLICY "Acceso total a pagos" ON public.pagos FOR ALL TO anon, authenticated USING (true) WITH CHECK (true);

    -- Mantenimientos
    DROP POLICY IF EXISTS "Acceso total a mantenimientos" ON public.mantenimientos;
    CREATE POLICY "Acceso total a mantenimientos" ON public.mantenimientos FOR ALL TO anon, authenticated USING (true) WITH CHECK (true);

    -- Alquileres
    DROP POLICY IF EXISTS "Acceso total a alquileres" ON public.alquileres;
    CREATE POLICY "Acceso total a alquileres" ON public.alquileres FOR ALL TO anon, authenticated USING (true) WITH CHECK (true);
END $$;
